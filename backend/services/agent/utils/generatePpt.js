function addContentSlide(
    ppt,
    title,
    points,
    page,
    total
) {
    const slide = ppt.addSlide()

    slide.background = {
        color: COLORS.white
    }

    // left accent
    slide.addShape(ppt.ShapeType.rect, {
        x: 0,
        y: 0,
        w: 0.1,
        h: 7.5,
        fill: {
            color: COLORS.primary
        },
        line: {
            color: COLORS.primary
        }
    })

    // top right decoration
    slide.addShape(ppt.ShapeType.ellipse, {
        x: 12.2,
        y: -0.55,
        w: 1.7,
        h: 1.7,
        fill: {
            color: COLORS.blueSoft,
            transparency: 35
        },
        line: {
            color: COLORS.blueSoft,
            transparency: 100
        }
    })

    slide.addShape(ppt.ShapeType.ellipse, {
        x: 11.85,
        y: 0.25,
        w: 0.12,
        h: 0.12,
        fill: {
            color: COLORS.primary
        },
        line: {
            color: COLORS.primary
        }
    })

    slide.addText(title, {
        x: 0.6,
        y: 0.35,
        w: 10.8,
        h: 0.4,
        fontSize: 24,
        bold: true,
        color: COLORS.primary,
        fit: "shrink"
    })

    slide.addShape(ppt.ShapeType.line, {
        x: 0.6,
        y: 0.85,
        w: 12,
        h: 0,
        line: {
            color: COLORS.border,
            width: 1.2
        }
    })

    const visiblePoints = Array.isArray(points)
        ? points.slice(0, 6)
        : []

    visiblePoints.forEach((point, i) => {
        const y = 1.2 + i * 0.75

        // content card
        slide.addShape(ppt.ShapeType.roundRect, {
            x: 0.7,
            y,
            w: 12,
            h: 0.58,
            rectRadius: 0.08,
            fill: {
                color: i % 2
                    ? COLORS.light
                    : COLORS.blueLight
            },
            line: {
                color: COLORS.border,
                width: 0.7
            }
        })

        // bullet
        slide.addShape(ppt.ShapeType.ellipse, {
            x: 0.92,
            y: y + 0.18,
            w: 0.12,
            h: 0.12,
            fill: {
                color: COLORS.primary
            },
            line: {
                color: COLORS.primary
            }
        })

        slide.addText(point, {
            x: 1.2,
            y: y + 0.08,
            w: 11,
            h: 0.35,
            fontSize: 15,
            color: COLORS.text,
            fit: "shrink",
            margin: 0
        })
    })

    // progress bar
    const progress = total > 0
        ? Math.min(page / total, 1)
        : 0

    slide.addShape(ppt.ShapeType.rect, {
        x: 9.7,
        y: 6.9,
        w: 2.1,
        h: 0.055,
        fill: {
            color: COLORS.border
        },
        line: {
            color: COLORS.border,
            transparency: 100
        }
    })

    slide.addShape(ppt.ShapeType.rect, {
        x: 9.7,
        y: 6.9,
        w: 2.1 * progress,
        h: 0.055,
        fill: {
            color: COLORS.primary
        },
        line: {
            color: COLORS.primary,
            transparency: 100
        }
    })

    slide.addText("Samanvay AI", {
        x: 0.6,
        y: 6.85,
        w: 2,
        h: 0.2,
        fontSize: 10,
        bold: true,
        color: COLORS.muted,
        margin: 0
    })

    slide.addText(`${page}/${total}`, {
        x: 12.1,
        y: 6.85,
        w: 0.65,
        h: 0.2,
        align: "right",
        fontSize: 10,
        color: COLORS.muted,
        margin: 0
    })
}

